// ota.h — обновление прошивки через протокол кошелька: по USB или по шифрованному
// каналу BLE (с телефона). Подлинность образа подтверждает человек (хеш на экране),
// а при Secure Boot ещё и загрузчик (подпись).
//   ota begin <размер> <sha256 hex>   -> подтверждение на экране
//   ota b64 <base64, до 2048 байт>     (столько раз, сколько нужно; есть с v0.5)
//   ota data <hex, до 1024 байт>       то же в hex — для старых хостов
//   ota end                            -> проверка хеша и образа (и подписи
//                                         при Secure Boot), перезагрузка
//   ota abort
#pragma once
#include <stdbool.h>

#include "app.h"

// На время передачи экран и кнопка принадлежат обновлению (app_busy). Обновление
// отменяется, если данных нет 30 с или пропала связь BLE, по которой оно шло.

// true, если строка — команда ota (тогда ответ уже отправлен). ble — пришла по BLE
bool ota_line(char *line, app_reply_fn reply, bool ble);
void ota_tick(void);       // звать из главного цикла
void ota_link_lost(void);  // соединение BLE закрыто
